using Docsum.Application.Abstractions;
using Docsum.Application.Common;
using Docsum.Domain;

namespace Docsum.Application.Documents;

public class DocumentService(
    IDocumentRepository documents,
    IFileStorage storage,
    IFolderRepository folders,
    IDocumentSummarizer summarizer)
{
    public const long MaxSizeBytes = 10 * 1024 * 1024;
    private static readonly byte[] PdfMagic = "%PDF-"u8.ToArray();

    public async Task<Result<DocumentListItemDto>> UploadAsync(
        int userId, string fileName, Stream content, long size, int? folderId,
        CancellationToken ct)
    {
        if (size <= 0) return Result<DocumentListItemDto>.Fail("File is empty.");
        if (size > MaxSizeBytes) return Result<DocumentListItemDto>.Fail("File is larger than 10 MB.");

        if (folderId is not null && await folders.GetAsync(userId, folderId.Value, ct) is null)
            return Result<DocumentListItemDto>.Fail("Folder not found.");

        // never trust the extension alone: check the first bytes
        var header = new byte[PdfMagic.Length];
        var read = await content.ReadAtLeastAsync(header, header.Length, throwOnEndOfStream: false, ct);
        if (read < header.Length || !header.AsSpan().SequenceEqual(PdfMagic))
            return Result<DocumentListItemDto>.Fail("Only PDF files are supported.");
        content.Position = 0;

        // Path.GetFileName strips any directory parts like "../../"
        var displayName = Path.GetFileName(fileName);
        if (displayName.Length > 255) displayName = displayName[..255];

        var storedName = $"{Guid.NewGuid():N}.pdf";   // generated by us, never from user input
        await storage.SaveAsync(storedName, content, ct);

        var document = new Document
        {
            UserId = userId,
            FolderId = folderId,
            FileName = displayName,
            StoredFileName = storedName,
            SizeBytes = size,
            Status = DocumentStatus.Uploaded
        };
        await documents.AddAsync(document, ct);

        return Result<DocumentListItemDto>.Ok(
            new(document.Id, document.FileName, document.FolderId, document.Status, document.CreatedAt));
    }

    public async Task<List<DocumentListItemDto>> ListAsync(int userId, CancellationToken ct) =>
        (await documents.ListAsync(userId, ct))
            .Select(d => new DocumentListItemDto(
                d.Id, d.FileName, d.FolderId, d.Status, d.CreatedAt))
            .ToList();

    public async Task<DocumentDetailDto?> GetAsync(int userId, int documentId, CancellationToken ct)
    {
        var d = await documents.GetAsync(userId, documentId, ct);
        return d is null ? null : ToDetail(d);
    }

    /// <summary>
    /// Regenerates the summary on demand. Useful when AI was configured after the
    /// document was processed, or when a previous summary attempt failed.
    /// </summary>
    public async Task<SummarizeOutcome> SummarizeAsync(
        int userId, int documentId, CancellationToken ct)
    {
        var document = await documents.GetAsync(userId, documentId, ct);
        if (document is null) return SummarizeOutcome.NotFound();

        if (document.Status != DocumentStatus.Done ||
            string.IsNullOrWhiteSpace(document.ExtractedText))
            return SummarizeOutcome.NotReady(
                "This document is still being processed. Try again shortly.");

        if (!summarizer.IsConfigured)
            return SummarizeOutcome.AiUnavailable(
                "AI is not configured. Set Ai:BaseUrl, Ai:Model and Ai:ApiKey in user-secrets.");

        string? summary;
        try
        {
            summary = await summarizer.SummarizeAsync(document.ExtractedText, ct);
        }
        catch (Exception ex)
        {
            // Keep any previous summary; only report the failure.
            return SummarizeOutcome.Failed($"Summary generation failed: {ex.Message}");
        }

        if (string.IsNullOrWhiteSpace(summary))
            return SummarizeOutcome.Failed("The AI returned an empty summary.");

        document.Summary = summary.Trim();
        await documents.SaveAsync(document, ct);

        return SummarizeOutcome.Ok(ToDetail(document));
    }

    private static DocumentDetailDto ToDetail(Document d) =>
        new(d.Id, d.FileName, d.FolderId, d.Status, d.CreatedAt, d.Summary, d.ErrorMessage);

    public async Task<Result<DocumentListItemDto>> MoveAsync(
        int userId, int documentId, int? folderId, CancellationToken ct)
    {
        var document = await documents.GetAsync(userId, documentId, ct);
        if (document is null) return Result<DocumentListItemDto>.Fail("Document not found.");

        if (folderId is not null && await folders.GetAsync(userId, folderId.Value, ct) is null)
            return Result<DocumentListItemDto>.Fail("Folder not found.");

        document.FolderId = folderId;
        await documents.SaveAsync(document, ct);

        return Result<DocumentListItemDto>.Ok(new DocumentListItemDto(
            document.Id, document.FileName, document.FolderId, document.Status, document.CreatedAt));
    }

    public async Task<bool> DeleteAsync(int userId, int documentId, CancellationToken ct)
    {
        var document = await documents.GetAsync(userId, documentId, ct);
        if (document is null) return false;

        await storage.DeleteAsync(document.StoredFileName, ct);
        await documents.DeleteAsync(document, ct);
        return true;
    }
}
